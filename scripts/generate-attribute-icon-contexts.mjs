import {writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {categoryOptions} from '../lib/catalog-config.ts';
import {resolveCategoryAttributeSchema} from '../lib/reference-data/category-attribute-schemas.ts';
// Category context comes from schema profiles, never from labels, user values or slug guesses.
const profileModels={
 smartphone:'Smartphone',tablet:'Tablet',ereader:'BookOpen',graphicsTablet:'Tablet',smartWatch:'Watch',
 laptop:'Laptop',computer:'Monitor',display:'Monitor',tv:'Tv',projector:'Projector',camera:'Camera',videoCamera:'Video',actionCamera:'Video',lens:'Camera',component:'CircuitBoard',
 commercialVehicle:'Truck',passengerCommercial:'Bus',machinery:'Tractor',watercraft:'Ship',aircraft:'Plane',electricPersonalTransport:'Bike',
 autoPart:'Wrench',motoPart:'Wrench',commercialPart:'Wrench',dismantling:'Wrench',
 appliance:'Settings2',laundryAppliance:'WashingMachine',dryingAppliance:'WashingMachine',refrigeratorAppliance:'Refrigerator',freezerAppliance:'Refrigerator',climateAppliance:'AirVent',fanAppliance:'Fan',cookerHobAppliance:'CookingPot',ovenAppliance:'CookingPot',microwaveAppliance:'Microwave',
 audio:'Headphones',gaming:'Gamepad2',equipment:'Factory',tool:'Drill',bicycle:'Bike',stroller:'Baby',clothing:'Shirt',shoes:'Footprints',furniture:'Sofa',
 // Mixed rental/exchange profiles retain a generic device/model instead of assuming one item type.
 rentalComputerProjector:'Monitor',rentalPhotoVideo:'Camera',rentalSoundLight:'Settings2',freePhoneComputer:'Monitor',exchangeMobileDevice:'Smartphone',
};
export function collectAttributeIconContexts(){
 const groups={};
 for(const category of categoryOptions){
  const schema=resolveCategoryAttributeSchema(category.slug,category.rootSlug);
  if(!schema.attributes.some(a=>['model','model_other','brand','brand_other'].includes(a.key)))continue;
  let icon;
  for(const profile of schema.profileNames){
   if(profile.startsWith('passengerCar'))icon='Car';
   else if(profile.startsWith('motorcycle'))icon=['motorcycleAtv','motorcycleUtv','motorcycleBuggy','motorcycleSnowmobile'].includes(profile)?'Cog':'Motorbike';
   else if(profileModels[profile])icon=profileModels[profile];
  }
  if(!icon)continue;
  (groups[icon]??=[]).push(category.slug);
 }
 return Object.fromEntries(Object.entries(groups).sort(([a],[b])=>a.localeCompare(b)).map(([icon,slugs])=>[icon,slugs.sort().join(' ')]));
}
export function renderAttributeIconContexts(){const groups=collectAttributeIconContexts();return '// Generated by scripts/generate-attribute-icon-contexts.mjs from Master Catalog schema profiles.\n// Only ambiguous brand/model fields need this small runtime lookup.\nexport const categoryModelIconGroups = '+JSON.stringify(groups,null,2)+' as const;\n';}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await writeFile(new URL('../lib/reference-data/attribute-icon-contexts.ts',import.meta.url),renderAttributeIconContexts());
