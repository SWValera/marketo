import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { attributeSets, categoryTree } from "../lib/catalog-config.ts";
import { KAZAKHSTAN, geographySource, regions } from "../lib/geography.ts";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(projectRoot, "supabase/seeds/001_marketo_reference.sql");

const q = (value) => value === null || value === undefined
  ? "null"
  : `'${String(value).replaceAll("'", "''")}'`;
const b = (value) => value ? "true" : "false";

const statements = [];
const add = (sql) => statements.push(sql.trim());

add(`
-- Marketo v1.0 reference seed. Generated by scripts/generate-reference-seeds.mjs.
-- Contains no users, listings, chats or other demo/product records.
-- Geography is a reviewed 90-city bootstrap plus 20 top-level units, not the
-- complete Kazakhstan settlement register. Use the reviewed KATO importer
-- before claiming coverage of every village, town and district.
-- Categories are the initial Marketo reference taxonomy and remain subject to
-- independent business review before production launch.

begin;

insert into public.locales (code, name_ru, name_kk, is_active, sort_order)
values
  ('ru', 'Русский', 'Орысша', true, 10),
  ('kk', 'Казахский', 'Қазақша', true, 20)
on conflict (code) do update set
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order;

insert into public.countries (
  code, slug, name_ru, name_kk, currency_code, currency_symbol,
  currency_exponent, phone_code, is_active, sort_order
)
values (
  ${q(KAZAKHSTAN.iso2)}, 'kazakhstan', ${q(KAZAKHSTAN.name.ru)},
  ${q(KAZAKHSTAN.name.kk)}, ${q(KAZAKHSTAN.currency)},
  ${q(KAZAKHSTAN.currencySymbol)}, 0, '+7', true, 10
)
on conflict (code) do update set
  slug = excluded.slug,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  currency_code = excluded.currency_code,
  currency_symbol = excluded.currency_symbol,
  currency_exponent = excluded.currency_exponent,
  phone_code = excluded.phone_code,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order;
`);

for (const [regionIndex, region] of regions.entries()) {
  add(`
insert into public.regions (
  country_id, code, slug, name_ru, name_kk, kind, is_active,
  sort_order, source_code, source_updated_at
)
values (
  (select id from public.countries where code = 'KZ'),
  ${q(region.id)}, ${q(region.id)}, ${q(region.name.ru)}, ${q(region.name.kk)},
  ${q(region.kind)}, true, ${(regionIndex + 1) * 10}, null, ${q(geographySource.updatedAt)}::date
)
on conflict (country_id, code) do update set
  slug = excluded.slug,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  kind = excluded.kind,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order,
  source_updated_at = excluded.source_updated_at;
`);

  for (const [settlementIndex, settlement] of region.settlements.entries()) {
    add(`
insert into public.settlements (
  region_id, parent_id, kato_code, slug, name_ru, name_kk, kind,
  is_selectable, is_active, sort_order, source_updated_at
)
values (
  (
    select region_row.id
    from public.regions as region_row
    join public.countries as country on country.id = region_row.country_id
    where country.code = 'KZ' and region_row.code = ${q(region.id)}
  ),
  null, ${q(settlement.kato ?? null)}, ${q(settlement.id)},
  ${q(settlement.name.ru)}, ${q(settlement.name.kk)}, 'city', true, true,
  ${(settlementIndex + 1) * 10}, ${q(geographySource.updatedAt)}::date
)
on conflict (region_id, slug) do update set
  kato_code = excluded.kato_code,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  kind = excluded.kind,
  is_selectable = excluded.is_selectable,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order,
  source_updated_at = excluded.source_updated_at;
`);
  }
}

function walkCategories(nodes, parent = null, inherited = {}) {
  for (const [index, node] of nodes.entries()) {
    const presentation = {
      searchPlaceholder: node.searchPlaceholder ?? inherited.searchPlaceholder,
      titlePlaceholder: node.titlePlaceholder ?? inherited.titlePlaceholder,
      descriptionHint: node.descriptionHint ?? inherited.descriptionHint,
      priceMode: node.priceMode ?? inherited.priceMode ?? "price",
      attributeSet: node.attributeSet ?? inherited.attributeSet ?? "goods",
      icon: node.icon ?? inherited.icon,
      tone: node.tone ?? inherited.tone,
    };

    add(`
insert into public.categories (
  parent_id, slug, name_ru, name_kk, icon_key, tone_key,
  search_placeholder_ru, search_placeholder_kk,
  title_placeholder_ru, title_placeholder_kk,
  description_hint_ru, description_hint_kk,
  price_mode, sort_order, is_active
)
values (
  ${parent ? `(select id from public.categories where slug = ${q(parent.slug)})` : "null"},
  ${q(node.slug)}, ${q(node.name.ru)}, ${q(node.name.kk)},
  ${q(presentation.icon)}, ${q(presentation.tone)},
  ${q(presentation.searchPlaceholder?.ru)}, ${q(presentation.searchPlaceholder?.kk)},
  ${q(presentation.titlePlaceholder?.ru)}, ${q(presentation.titlePlaceholder?.kk)},
  ${q(presentation.descriptionHint?.ru)}, ${q(presentation.descriptionHint?.kk)},
  ${q(presentation.priceMode)}, ${(index + 1) * 10}, true
)
on conflict (slug) do update set
  parent_id = excluded.parent_id,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  icon_key = excluded.icon_key,
  tone_key = excluded.tone_key,
  search_placeholder_ru = excluded.search_placeholder_ru,
  search_placeholder_kk = excluded.search_placeholder_kk,
  title_placeholder_ru = excluded.title_placeholder_ru,
  title_placeholder_kk = excluded.title_placeholder_kk,
  description_hint_ru = excluded.description_hint_ru,
  description_hint_kk = excluded.description_hint_kk,
  price_mode = excluded.price_mode,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active;
`);

    // Marketo v1 stores the effective attribute set on every category. This is
    // intentionally explicit: UI queries never need ambiguous multi-level
    // inheritance, while the schema can still support curated inheritance later.
    const definitions = attributeSets[presentation.attributeSet];
    for (const [attributeIndex, attribute] of definitions.entries()) {
      const dataType = attribute.type === "checkbox" ? "boolean" : attribute.type;
      add(`
insert into public.category_attributes (
  category_id, key, label_ru, label_kk, data_type, unit_ru, unit_kk,
  is_required, is_filterable, is_searchable, inherits_to_children,
  validation, sort_order, is_active
)
values (
  (select id from public.categories where slug = ${q(node.slug)}),
  ${q(attribute.id)}, ${q(attribute.label.ru)}, ${q(attribute.label.kk)},
  ${q(dataType)}, ${q(attribute.unit?.ru)}, ${q(attribute.unit?.kk)},
  ${b(attribute.required)}, ${b(attribute.filterable)}, ${b(attribute.type === "text")},
  false, '{}'::jsonb, ${(attributeIndex + 1) * 10}, true
)
on conflict (category_id, key) do update set
  label_ru = excluded.label_ru,
  label_kk = excluded.label_kk,
  data_type = excluded.data_type,
  unit_ru = excluded.unit_ru,
  unit_kk = excluded.unit_kk,
  is_required = excluded.is_required,
  is_filterable = excluded.is_filterable,
  is_searchable = excluded.is_searchable,
  inherits_to_children = excluded.inherits_to_children,
  validation = excluded.validation,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active;
`);

      for (const [optionIndex, option] of (attribute.options ?? []).entries()) {
        add(`
insert into public.category_attribute_options (
  attribute_id, value, label_ru, label_kk, sort_order, is_active
)
values (
  (
    select attribute_row.id
    from public.category_attributes as attribute_row
    join public.categories as category on category.id = attribute_row.category_id
    where category.slug = ${q(node.slug)} and attribute_row.key = ${q(attribute.id)}
  ),
  ${q(option.value)}, ${q(option.label.ru)}, ${q(option.label.kk)},
  ${(optionIndex + 1) * 10}, true
)
on conflict (attribute_id, value) do update set
  label_ru = excluded.label_ru,
  label_kk = excluded.label_kk,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active;
`);
      }
    }

    if (node.children?.length) walkCategories(node.children, node, presentation);
  }
}

walkCategories(categoryTree);
add("commit;");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${statements.join("\n\n")}\n`, "utf8");

const categoryCount = statements.filter((item) => item.startsWith("insert into public.categories ")).length;
const attributeCount = statements.filter((item) => item.startsWith("insert into public.category_attributes ")).length;
const optionCount = statements.filter((item) => item.startsWith("insert into public.category_attribute_options ")).length;
const settlementCount = regions.reduce((total, region) => total + region.settlements.length, 0);
process.stdout.write(`Generated ${outputPath}\n${regions.length} regions, ${settlementCount} cities, ${categoryCount} categories, ${attributeCount} attributes, ${optionCount} options\n`);
