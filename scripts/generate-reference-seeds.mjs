import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { categoryTree } from "../lib/catalog-config.ts";
import { resolveCategoryAttributeSchema } from "../lib/reference-data/category-attribute-schemas.ts";
import { KAZAKHSTAN, geographySource, regions } from "../lib/geography.ts";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputArgumentIndex = process.argv.indexOf("--output");
if (outputArgumentIndex >= 0 && !process.argv[outputArgumentIndex + 1]) {
  throw new Error("--output requires a destination path.");
}
const outputPath = outputArgumentIndex >= 0
  ? resolve(projectRoot, process.argv[outputArgumentIndex + 1])
  : resolve(projectRoot, "supabase/seeds/001_marketo_reference.sql");

const q = (value) => value === null || value === undefined
  ? "null"
  : `'${String(value).replaceAll("'", "''")}'`;
const b = (value) => value ? "true" : "false";
const chunks = (rows, size = 300) => Array.from({ length: Math.ceil(rows.length / size) }, (_, index) => rows.slice(index * size, (index + 1) * size));

const statements = [];
const add = (sql) => statements.push(sql.trim());
const attributeRows = [];
const optionRows = [];
let categoryCount = 0;

add(`
-- Marketo v1.0 reference seed. Generated by scripts/generate-reference-seeds.mjs.
-- Contains no users, listings, chats or other demo/product records.
-- Geography is a reviewed 90-city bootstrap plus 20 top-level units, not the
-- complete Kazakhstan settlement register. Use the reviewed KATO importer
-- before claiming coverage of every village, town and district.
-- Categories and attributes are the reviewed Marketo v1.0 reference taxonomy.
-- Runtime UI reads these rows from Supabase; no product/demo records are seeded.

begin;

insert into public.locales (code, name_ru, name_kk, is_active, sort_order)
values
  ('ru', 'Русский', 'Орысша', true, 10),
  ('kk', 'Казахский', 'Қазақша', true, 20)
on conflict (code) do update set
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order;

insert into public.countries (
  code, slug, name_ru, name_kk, currency_code, currency_symbol,
  currency_exponent, phone_code, is_active, sort_order
)
values (
  ${q(KAZAKHSTAN.iso2)}, 'kazakhstan', ${q(KAZAKHSTAN.name.ru)},
  ${q(KAZAKHSTAN.name.kk)}, ${q(KAZAKHSTAN.currency)},
  ${q(KAZAKHSTAN.currencySymbol)}, 0, '+7', true, 10
)
on conflict (code) do update set
  slug = excluded.slug,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  currency_code = excluded.currency_code,
  currency_symbol = excluded.currency_symbol,
  currency_exponent = excluded.currency_exponent,
  phone_code = excluded.phone_code,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order;
`);

for (const [regionIndex, region] of regions.entries()) {
  add(`
insert into public.regions (
  country_id, code, slug, name_ru, name_kk, kind, is_active,
  sort_order, source_code, source_updated_at
)
values (
  (select id from public.countries where code = 'KZ'),
  ${q(region.id)}, ${q(region.id)}, ${q(region.name.ru)}, ${q(region.name.kk)},
  ${q(region.kind)}, true, ${(regionIndex + 1) * 10}, null, ${q(geographySource.updatedAt)}::date
)
on conflict (country_id, code) do update set
  slug = excluded.slug,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  kind = excluded.kind,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order,
  source_updated_at = excluded.source_updated_at;
`);

  for (const [settlementIndex, settlement] of region.settlements.entries()) {
    add(`
insert into public.settlements (
  region_id, parent_id, kato_code, slug, name_ru, name_kk, kind,
  is_selectable, is_active, sort_order, source_updated_at
)
values (
  (
    select region_row.id
    from public.regions as region_row
    join public.countries as country on country.id = region_row.country_id
    where country.code = 'KZ' and region_row.code = ${q(region.id)}
  ),
  null, ${q(settlement.kato ?? null)}, ${q(settlement.id)},
  ${q(settlement.name.ru)}, ${q(settlement.name.kk)}, 'city', true, true,
  ${(settlementIndex + 1) * 10}, ${q(geographySource.updatedAt)}::date
)
on conflict (region_id, slug) do update set
  kato_code = excluded.kato_code,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  kind = excluded.kind,
  is_selectable = excluded.is_selectable,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order,
  source_updated_at = excluded.source_updated_at;
`);
  }
}

function walkCategories(nodes, parent = null, inherited = {}, rootSlug = null) {
  for (const [index, node] of nodes.entries()) {
    categoryCount += 1;
    const actualRootSlug = rootSlug ?? node.slug;
    const presentation = {
      searchPlaceholder: node.searchPlaceholder ?? inherited.searchPlaceholder,
      titlePlaceholder: node.titlePlaceholder ?? inherited.titlePlaceholder,
      descriptionHint: node.descriptionHint ?? inherited.descriptionHint,
      priceMode: node.priceMode ?? inherited.priceMode ?? "price",
      icon: node.icon ?? inherited.icon,
      tone: node.tone ?? inherited.tone,
    };

    add(`
insert into public.categories (
  parent_id, slug, name_ru, name_kk, icon_key, tone_key,
  search_placeholder_ru, search_placeholder_kk,
  title_placeholder_ru, title_placeholder_kk,
  description_hint_ru, description_hint_kk,
  price_mode, sort_order, is_active
)
values (
  ${parent ? `(select id from public.categories where slug = ${q(parent.slug)})` : "null"},
  ${q(node.slug)}, ${q(node.name.ru)}, ${q(node.name.kk)},
  ${q(presentation.icon)}, ${q(presentation.tone)},
  ${q(presentation.searchPlaceholder?.ru)}, ${q(presentation.searchPlaceholder?.kk)},
  ${q(presentation.titlePlaceholder?.ru)}, ${q(presentation.titlePlaceholder?.kk)},
  ${q(presentation.descriptionHint?.ru)}, ${q(presentation.descriptionHint?.kk)},
  ${q(presentation.priceMode)}, ${(index + 1) * 10}, true
)
on conflict (slug) do update set
  parent_id = excluded.parent_id,
  name_ru = excluded.name_ru,
  name_kk = excluded.name_kk,
  icon_key = excluded.icon_key,
  tone_key = excluded.tone_key,
  search_placeholder_ru = excluded.search_placeholder_ru,
  search_placeholder_kk = excluded.search_placeholder_kk,
  title_placeholder_ru = excluded.title_placeholder_ru,
  title_placeholder_kk = excluded.title_placeholder_kk,
  description_hint_ru = excluded.description_hint_ru,
  description_hint_kk = excluded.description_hint_kk,
  price_mode = excluded.price_mode,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active;
`);

    // Profiles are composed once here; Supabase is the runtime source of truth.
    const { attributes: definitions } = resolveCategoryAttributeSchema(node.slug, actualRootSlug);
    for (const [attributeIndex, attribute] of definitions.entries()) {
      attributeRows.push([
        node.slug, attribute.key, attribute.label.ru, attribute.label.kk, attribute.dataType,
        attribute.unit?.ru ?? null, attribute.unit?.kk ?? null, Boolean(attribute.required),
        Boolean(attribute.filterable), Boolean(attribute.searchable), false,
        JSON.stringify(attribute.validation ?? {}), attribute.filterMode ?? "exact",
        attribute.optionsLoadMode ?? "eager", attribute.dependsOnKey ?? null, true,
        (attributeIndex + 1) * 10,
      ]);
      (attribute.options ?? []).forEach((option, optionIndex) => optionRows.push([
        node.slug, attribute.key, option.value, option.label.ru, option.label.kk,
        option.parentValue ?? null, (optionIndex + 1) * 10,
      ]));
    }

    if (node.children?.length) walkCategories(node.children, node, presentation, actualRootSlug);
  }
}

walkCategories(categoryTree);
add(`
create temporary table marketo_seed_attributes (
  category_slug text not null, key text not null, label_ru text not null,
  label_kk text not null, data_type text not null, unit_ru text, unit_kk text,
  is_required boolean not null, is_filterable boolean not null,
  is_searchable boolean not null, inherits_to_children boolean not null,
  validation jsonb not null, filter_mode text not null,
  options_load_mode text not null, depends_on_key text, is_visible boolean not null,
  sort_order integer not null, primary key (category_slug, key)
) on commit drop;

create temporary table marketo_seed_options (
  category_slug text not null, attribute_key text not null, value text not null,
  label_ru text not null, label_kk text not null, parent_value text,
  sort_order integer not null, primary key (category_slug, attribute_key, value)
) on commit drop;
`);
for (const chunk of chunks(attributeRows)) {
  add(`insert into marketo_seed_attributes values\n${chunk.map((row) => `(${row.map((value, index) => index === 7 || index === 8 || index === 9 || index === 10 || index === 15 ? b(value) : index === 11 ? `${q(value)}::jsonb` : q(value)).join(", ")})`).join(",\n")};`);
}
for (const chunk of chunks(optionRows)) {
  add(`insert into marketo_seed_options values\n${chunk.map((row) => `(${row.map(q).join(", ")})`).join(",\n")};`);
}
add(`
insert into public.category_attributes (
  category_id, key, label_ru, label_kk, data_type, unit_ru, unit_kk,
  is_required, is_filterable, is_searchable, inherits_to_children,
  validation, filter_mode, options_load_mode, depends_on_key, is_visible,
  sort_order, is_active
)
select category.id, seed.key, seed.label_ru, seed.label_kk, seed.data_type,
  seed.unit_ru, seed.unit_kk, seed.is_required, seed.is_filterable,
  seed.is_searchable, seed.inherits_to_children, seed.validation,
  seed.filter_mode, seed.options_load_mode, seed.depends_on_key,
  seed.is_visible, seed.sort_order, true
from marketo_seed_attributes as seed
join public.categories as category on category.slug = seed.category_slug
on conflict (category_id, key) do update set
  label_ru = excluded.label_ru, label_kk = excluded.label_kk,
  data_type = excluded.data_type, unit_ru = excluded.unit_ru,
  unit_kk = excluded.unit_kk, is_required = excluded.is_required,
  is_filterable = excluded.is_filterable, is_searchable = excluded.is_searchable,
  inherits_to_children = excluded.inherits_to_children,
  validation = excluded.validation, filter_mode = excluded.filter_mode,
  options_load_mode = excluded.options_load_mode,
  depends_on_key = excluded.depends_on_key, is_visible = excluded.is_visible,
  sort_order = excluded.sort_order, is_active = true;

insert into public.category_attribute_options (
  attribute_id, value, label_ru, label_kk, parent_option_id, sort_order, is_active
)
select attribute.id, seed.value, seed.label_ru, seed.label_kk, null,
  seed.sort_order, true
from marketo_seed_options as seed
join public.categories as category on category.slug = seed.category_slug
join public.category_attributes as attribute
  on attribute.category_id = category.id and attribute.key = seed.attribute_key
on conflict (attribute_id, value) do update set
  label_ru = excluded.label_ru, label_kk = excluded.label_kk,
  parent_option_id = null, sort_order = excluded.sort_order, is_active = true;

update public.category_attribute_options as child_option
set parent_option_id = parent_option.id
from marketo_seed_options as seed
join public.categories as category on category.slug = seed.category_slug
join public.category_attributes as child_attribute
  on child_attribute.category_id = category.id and child_attribute.key = seed.attribute_key
join public.category_attributes as parent_attribute
  on parent_attribute.category_id = category.id
 and parent_attribute.key = child_attribute.depends_on_key
join public.category_attribute_options as parent_option
  on parent_option.attribute_id = parent_attribute.id
 and parent_option.value = seed.parent_value
where seed.parent_value is not null
  and child_option.attribute_id = child_attribute.id
  and child_option.value = seed.value;

-- 0020 owns the contextual RU/KK helper-text source of truth. Reapply it
-- after idempotent category upserts so seed reruns cannot restore broad examples.
select private.apply_contextual_catalog_metadata();
`);
add("commit;");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${statements.join("\n\n")}\n`, "utf8");

const settlementCount = regions.reduce((total, region) => total + region.settlements.length, 0);
process.stdout.write(`Generated ${outputPath}\n${regions.length} regions, ${settlementCount} cities, ${categoryCount} categories, ${attributeRows.length} attributes, ${optionRows.length} options\n`);
